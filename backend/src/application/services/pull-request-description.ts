import { CoveragePercentage } from '../../domain/coverage/coverage-percentage';
import { FilePath } from '../../domain/coverage/file-path';
import { TestPlan } from '../../domain/job/test-plan';

export interface PullRequestDescriptionInput {
  jobId: string;
  targetFile: FilePath;
  coverageBefore: CoveragePercentage;
  coverageAfter: CoveragePercentage;
  branchesBefore: CoveragePercentage;
  branchesAfter: CoveragePercentage;
  plan: TestPlan;
  testFiles: string[];
  /** How many identical, passing runs the verification required (VERIFY_RUNS). */
  verificationRuns: number;
  /** Non-test files the AI changed and the pipeline reverted. */
  revertedFiles: readonly string[];
  aiCostUsd: number;
}

const delta = (before: CoveragePercentage, after: CoveragePercentage): string => {
  const value = Math.round((after.value - before.value) * 100) / 100;
  return `${value >= 0 ? '+' : ''}${value.toFixed(2)} pp`;
};

const escapeCell = (text: string): string => text.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

/** Builds the commit message, PR title and PR body (Markdown) for a verified improvement. */
export class PullRequestDescription {
  constructor(private readonly input: PullRequestDescriptionInput) {}

  get commitMessage(): string {
    return `test: improve coverage of ${this.input.targetFile.value}\n\nGenerated by TS Coverage Improver (job ${this.input.jobId}).`;
  }

  get title(): string {
    const { targetFile, coverageBefore, coverageAfter } = this.input;
    return `test: improve coverage of ${targetFile.value} (${coverageBefore.toString()} → ${coverageAfter.toString()})`;
  }

  get body(): string {
    const {
      targetFile,
      coverageBefore,
      coverageAfter,
      branchesBefore,
      branchesAfter,
      plan,
      testFiles,
      jobId,
    } = this.input;
    const cases = plan.cases.map((c) => `| ${escapeCell(c.name)} | ${escapeCell(c.covers)} |`).join('\n');
    const runs = this.input.verificationRuns;
    const reverted = this.input.revertedFiles;
    return [
      `Automated test improvement for \`${targetFile.value}\`.`,
      '',
      '## Coverage',
      '',
      '| Metric | Before | After | Change |',
      '| --- | --- | --- | --- |',
      `| Lines | ${coverageBefore.toString()} | ${coverageAfter.toString()} | ${delta(coverageBefore, coverageAfter)} |`,
      `| Branches | ${branchesBefore.toString()} | ${branchesAfter.toString()} | ${delta(branchesBefore, branchesAfter)} |`,
      '',
      '## Test plan',
      '',
      plan.summary,
      '',
      '| Test | Covers |',
      '| --- | --- |',
      cases,
      '',
      '## Changed files',
      '',
      ...testFiles.map((file) => `- \`${file}\``),
      '',
      '## Verification',
      '',
      'Checked automatically before this PR was opened:',
      '- only `*.test.ts` files were added or modified;',
      runs > 1
        ? `- the related Jest tests pass in ${runs} consecutive runs with identical coverage (flaky check);`
        : '- the related Jest tests pass;',
      '- line coverage of the target file increased.',
      ...(reverted.length > 0
        ? [
            '',
            `${reverted.length} non-test edit${reverted.length === 1 ? ' was' : 's were'} made by the AI and reverted ` +
              'before verification (not part of this PR):',
            ...reverted.map((file) => `- \`${file}\``),
          ]
        : []),
      '',
      `<sub>Job \`${jobId}\` · AI cost $${this.input.aiCostUsd.toFixed(2)} · generated by TS Coverage Improver with an ` +
        'AI agent; please review before merging.</sub>',
    ].join('\n');
  }
}
