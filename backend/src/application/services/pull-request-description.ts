import { CoveragePercentage } from '../../domain/coverage/coverage-percentage';
import { FilePath } from '../../domain/coverage/file-path';
import { TestPlan } from '../../domain/job/test-plan';

export interface PullRequestDescriptionInput {
  jobId: string;
  targetFile: FilePath;
  coverageBefore: CoveragePercentage;
  coverageAfter: CoveragePercentage;
  plan: TestPlan;
  testFiles: string[];
}

const escapeCell = (text: string): string => text.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

/** Builds the commit message, PR title and PR body (Markdown) for a verified improvement. */
export class PullRequestDescription {
  constructor(private readonly input: PullRequestDescriptionInput) {}

  get commitMessage(): string {
    return `test: improve coverage of ${this.input.targetFile.value}\n\nGenerated by TS Coverage Improver (job ${this.input.jobId}).`;
  }

  get title(): string {
    const { targetFile, coverageBefore, coverageAfter } = this.input;
    return `test: improve coverage of ${targetFile.value} (${coverageBefore.toString()} → ${coverageAfter.toString()})`;
  }

  get body(): string {
    const { targetFile, coverageBefore, coverageAfter, plan, testFiles, jobId } = this.input;
    const delta = Math.round((coverageAfter.value - coverageBefore.value) * 100) / 100;
    const cases = plan.cases.map((c) => `| ${escapeCell(c.name)} | ${escapeCell(c.covers)} |`).join('\n');
    return [
      `Automated test improvement for \`${targetFile.value}\`.`,
      '',
      '## Coverage (lines)',
      '',
      '| Before | After | Change |',
      '| --- | --- | --- |',
      `| ${coverageBefore.toString()} | ${coverageAfter.toString()} | +${delta.toFixed(2)} pp |`,
      '',
      '## Test plan',
      '',
      plan.summary,
      '',
      '| Test | Covers |',
      '| --- | --- |',
      cases,
      '',
      '## Changed files',
      '',
      ...testFiles.map((file) => `- \`${file}\``),
      '',
      '## Verification',
      '',
      'Checked automatically before this PR was opened:',
      '- only `*.test.ts` files were added or modified;',
      '- the related Jest tests pass;',
      '- line coverage of the target file increased.',
      '',
      `<sub>Job \`${jobId}\` · generated by TS Coverage Improver with an AI agent; please review before merging.</sub>`,
    ].join('\n');
  }
}
